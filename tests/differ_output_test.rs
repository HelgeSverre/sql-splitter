fn data(added: u64, removed: u64, modified: u64) -> DataDiff {
    let mut tables = HashMap::new();
    tables.insert(
        "users".to_string(),
        TableDataDiff {
            old_row_count: 5,
            new_row_count: 5,
            added_count: added,
            removed_count: removed,
            modified_count: modified,
            truncated: false,
            sample_added_pks: vec![],
            sample_removed_pks: vec![],
            sample_modified_pks: vec![],
        },
    );
    DataDiff { tables }
}

#[test]
fn sql_data_changes_noted_only_when_schema_changed() {
    let mut m = modification("t");
    m.columns_added = vec![col("x", "INT", true)];
    let schema = SchemaDiff {
        tables_added: vec![],
        tables_removed: vec![],
        tables_modified: vec![m],
    };

    let r = result(Some(schema), Some(data(1, 0, 0)));
    let out = sql(&r, SqlDialect::MySql);
    assert_line(
        &out,
        "-- Data changes detected but not included in migration script",
    );
    assert_line(
        &out,
        "-- Use text or JSON output format for data diff details",
    );

    // Zero-change data diff must not produce the note.
    let mut m2 = modification("t");
    m2.columns_added = vec![col("x", "INT", true)];
    let r = result(
        Some(SchemaDiff {
            tables_added: vec![],
            tables_removed: vec![],
            tables_modified: vec![m2],
        }),
        Some(data(0, 0, 0)),
    );
    assert!(!sql(&r, SqlDialect::MySql).contains("Data changes detected"));

    // Data-only diff (no schema) short-circuits before the data note.
    let r = result(None, Some(data(1, 2, 3)));
    let out = sql(&r, SqlDialect::MySql);
    assert!(out.contains("No schema changes detected"));
    assert!(!out.contains("Data changes detected"), "{out}");
}

