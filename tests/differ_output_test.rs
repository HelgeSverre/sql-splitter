#[test]
fn text_modified_column_and_pk_lines() {
    let mut m = modification("users");
    m.columns_added = vec![col("email", "TEXT", false)];
    m.columns_removed = vec![col("legacy", "INT", true)];
    m.columns_modified = vec![
        ColumnChange {
            name: "age".into(),
            old_type: Some("INT".into()),
            new_type: Some("BIGINT".into()),
            old_nullable: Some(true),
            new_nullable: Some(false),
        },
        ColumnChange {
            name: "nick".into(),
            old_type: None,
            new_type: None,
            old_nullable: Some(false),
            new_nullable: Some(true),
        },
    ];
    m.pk_changed = true;
    m.old_pk = Some(strs(&["id"]));
    m.new_pk = None;
    m.fks_added = vec![fk(Some("fk1"))];
    m.fks_removed = vec![fk(None)];
    let out = text(&schema_with(m));
    assert_line(&out, "  ~ Table 'users':");
    assert_line(&out, "      + Column 'email' TEXT NOT NULL");
    assert_line(&out, "      - Column 'legacy' INT");
    assert_line(&out, "      ~ Column 'age': INT → BIGINT, NULL → NOT NULL");
    assert_line(&out, "      ~ Column 'nick': NOT NULL → NULL");
    assert_line(&out, "      ~ PRIMARY KEY: (id) → ((none))");
    assert_line(&out, "      + FK (a, b) → parent.(x, y)");
    assert_line(&out, "      - FK (a, b) → parent.(x, y)");
}

