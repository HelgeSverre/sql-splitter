fn pk_change(old: Option<&[&str]>, new: Option<&[&str]>) -> DiffResult {
    let mut m = modification("t");
    m.pk_changed = true;
    m.old_pk = old.map(strs);
    m.new_pk = new.map(strs);
    schema_with(m)
}

#[test]
fn sql_pk_change_mysql() {
    let out = sql(
        &pk_change(Some(&["id"]), Some(&["a", "b"])),
        SqlDialect::MySql,
    );
    assert_line(
        &out,
        "-- WARNING: PRIMARY KEY change (id) -> (a, b) may require table recreation",
    );
    assert_line(&out, "ALTER TABLE `t` DROP PRIMARY KEY;");
    assert_line(&out, "ALTER TABLE `t` ADD PRIMARY KEY (`a`, `b`);");
}

#[test]
fn sql_pk_change_postgres_and_mssql_drop_named_constraint() {
    let r = pk_change(Some(&["id"]), Some(&["uuid"]));
    let pg = sql(&r, SqlDialect::Postgres);
    assert_line(&pg, "ALTER TABLE \"t\" DROP CONSTRAINT IF EXISTS t_pkey;");
    assert_line(&pg, "ALTER TABLE \"t\" ADD PRIMARY KEY (\"uuid\");");

    let ms = sql(&r, SqlDialect::Mssql);
    assert_line(&ms, "ALTER TABLE [t] DROP CONSTRAINT IF EXISTS t_pkey;");
    assert_line(&ms, "ALTER TABLE [t] ADD PRIMARY KEY ([uuid]);");
}

#[test]
fn sql_pk_change_sqlite_skips_ddl() {
    let out = sql(
        &pk_change(Some(&["id"]), Some(&["uuid"])),
        SqlDialect::Sqlite,
    );
    assert_line(
        &out,
        "-- SQLite does not support ALTER PRIMARY KEY; table recreation required",
    );
    assert!(!out.contains("ADD PRIMARY KEY"), "{out}");
    assert!(!out.contains("DROP PRIMARY KEY"), "{out}");
}

#[test]
fn sql_pk_removed_only_drops() {
    // new_pk None -> "(none)" and no ADD PRIMARY KEY.
    let out = sql(&pk_change(Some(&["id"]), None), SqlDialect::MySql);
    assert_line(
        &out,
        "-- WARNING: PRIMARY KEY change (id) -> ((none)) may require table recreation",
    );
    assert_line(&out, "ALTER TABLE `t` DROP PRIMARY KEY;");
    assert!(!out.contains("ADD PRIMARY KEY"), "{out}");

    // Empty new_pk vec behaves the same as None for the ADD step.
    let out = sql(&pk_change(None, Some(&[])), SqlDialect::Postgres);
    assert_line(
        &out,
        "-- WARNING: PRIMARY KEY change ((none)) -> () may require table recreation",
    );
    assert!(!out.contains("ADD PRIMARY KEY"), "{out}");
}

#[test]
fn sql_pk_only_change_still_emits_table_header() {
    let out = sql(
        &pk_change(Some(&["id"]), Some(&["uuid"])),
        SqlDialect::MySql,
    );
    assert_line(&out, "-- Modified table: t");
}

