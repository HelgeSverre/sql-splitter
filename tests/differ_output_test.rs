fn idx(name: &str, unique: bool, ty: Option<&str>) -> IndexInfo {
    IndexInfo {
        name: name.into(),
        columns: strs(&["c1", "c2"]),
        is_unique: unique,
        index_type: ty.map(String::from),
    }
}

#[test]
fn sql_create_index_per_dialect() {
    let mut m = modification("t");
    m.indexes_added = vec![
        idx("ix_plain", false, None),
        idx("ix_uniq", true, Some("BTREE")),
    ];
    let r = schema_with(m);
    for d in ALL {
        let out = sql(&r, d);
        let cols = format!("{}, {}", q(d, "c1"), q(d, "c2"));
        // Only Postgres emits USING; other dialects ignore index_type.
        let using = if d == SqlDialect::Postgres {
            " USING btree"
        } else {
            ""
        };
        assert_line(
            &out,
            &format!(
                "CREATE INDEX {} ON {}({cols});",
                q(d, "ix_plain"),
                q(d, "t")
            ),
        );
        assert_line(
            &out,
            &format!(
                "CREATE UNIQUE INDEX {} ON {}{using}({cols});",
                q(d, "ix_uniq"),
                q(d, "t")
            ),
        );
    }
}

#[test]
fn sql_drop_index_per_dialect() {
    let mut m = modification("t");
    m.indexes_removed = vec![idx("ix_old", false, None)];
    let r = schema_with(m);
    assert_line(&sql(&r, SqlDialect::MySql), "DROP INDEX `ix_old` ON `t`;");
    assert_line(&sql(&r, SqlDialect::Mssql), "DROP INDEX [ix_old] ON [t];");
    assert_line(
        &sql(&r, SqlDialect::Postgres),
        "DROP INDEX IF EXISTS \"ix_old\";",
    );
    assert_line(
        &sql(&r, SqlDialect::Sqlite),
        "DROP INDEX IF EXISTS \"ix_old\";",
    );
}

