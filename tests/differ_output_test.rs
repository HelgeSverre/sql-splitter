//! Exact-output tests for the differ SQL and text formatters.
//!
//! Every test builds a `DiffResult` by hand and pins the emitted lines so a
//! change in quoting, keyword choice, or dialect branching fails loudly.

use sql_splitter::differ::{
    format_diff, ColumnChange, ColumnInfo, DataDiff, DiffOutputFormat, DiffResult, DiffSummary,
    FkInfo, IndexInfo, SchemaDiff, TableDataDiff, TableInfo, TableModification,
};
use sql_splitter::parser::SqlDialect;
use std::collections::HashMap;

const ALL: [SqlDialect; 4] = [
    SqlDialect::MySql,
    SqlDialect::Postgres,
    SqlDialect::Sqlite,
    SqlDialect::Mssql,
];

fn summary() -> DiffSummary {
    DiffSummary {
        tables_added: 0,
        tables_removed: 0,
        tables_modified: 0,
        rows_added: 0,
        rows_removed: 0,
        rows_modified: 0,
        truncated: false,
    }
}

fn result(schema: Option<SchemaDiff>, data: Option<DataDiff>) -> DiffResult {
    DiffResult {
        schema,
        data,
        warnings: vec![],
        summary: summary(),
    }
}

fn schema_with(m: TableModification) -> DiffResult {
    result(
        Some(SchemaDiff {
            tables_added: vec![],
            tables_removed: vec![],
            tables_modified: vec![m],
        }),
        None,
    )
}

fn modification(table: &str) -> TableModification {
    TableModification {
        table_name: table.to_string(),
        columns_added: vec![],
        columns_removed: vec![],
        columns_modified: vec![],
        pk_changed: false,
        old_pk: None,
        new_pk: None,
        fks_added: vec![],
        fks_removed: vec![],
        indexes_added: vec![],
        indexes_removed: vec![],
    }
}

fn col(name: &str, ty: &str, nullable: bool) -> ColumnInfo {
    ColumnInfo {
        name: name.to_string(),
        col_type: ty.to_string(),
        is_nullable: nullable,
        is_primary_key: false,
    }
}

fn strs(v: &[&str]) -> Vec<String> {
    v.iter().map(|s| s.to_string()).collect()
}

fn sql(r: &DiffResult, d: SqlDialect) -> String {
    format_diff(r, DiffOutputFormat::Sql, d)
}

fn text(r: &DiffResult) -> String {
    format_diff(r, DiffOutputFormat::Text, SqlDialect::MySql)
}

/// Quote `name` the way each dialect's formatter does.
fn q(d: SqlDialect, name: &str) -> String {
    match d {
        SqlDialect::MySql => format!("`{name}`"),
        SqlDialect::Postgres | SqlDialect::Sqlite => format!("\"{name}\""),
        SqlDialect::Mssql => format!("[{name}]"),
    }
}

fn assert_line(out: &str, line: &str) {
    assert!(
        out.lines().any(|l| l == line),
        "expected line {line:?} in output:\n{out}"
    );
}

