#[test]
fn sql_header_names_dialect() {
    let r = result(None, None);
    for d in ALL {
        let out = sql(&r, d);
        assert_eq!(
            out,
            format!(
                "-- SQL Migration Script\n-- Generated by sql-splitter diff (dialect: {d})\n--\n\n-- No schema changes detected\n"
            )
        );
    }
}

#[test]
fn sql_empty_schema_diff_reports_no_changes() {
    let r = result(
        Some(SchemaDiff {
            tables_added: vec![],
            tables_removed: vec![],
            tables_modified: vec![],
        }),
        None,
    );
    let out = sql(&r, SqlDialect::Postgres);
    assert!(out.ends_with("-- No schema changes detected\n"));
    assert!(!out.contains("ALTER"));
}

#[test]
fn sql_skips_modification_without_changes() {
    // A TableModification with nothing set must not emit a header.
    let r = schema_with(modification("noop"));
    let out = sql(&r, SqlDialect::MySql);
    assert!(!out.contains("Modified table: noop"), "{out}");
}

