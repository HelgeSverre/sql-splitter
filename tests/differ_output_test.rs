fn fk(name: Option<&str>) -> FkInfo {
    FkInfo {
        name: name.map(String::from),
        columns: strs(&["a", "b"]),
        referenced_table: "parent".into(),
        referenced_columns: strs(&["x", "y"]),
    }
}

#[test]
fn sql_add_fk_named_and_unnamed_per_dialect() {
    let mut m = modification("child");
    m.fks_added = vec![fk(Some("fk_child")), fk(None)];
    let r = schema_with(m);
    for d in ALL {
        let out = sql(&r, d);
        let cols = format!("{}, {}", q(d, "a"), q(d, "b"));
        let refs = format!("{}, {}", q(d, "x"), q(d, "y"));
        assert_line(
            &out,
            &format!(
                "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({cols}) REFERENCES {}({refs});",
                q(d, "child"),
                q(d, "fk_child"),
                q(d, "parent")
            ),
        );
        assert_line(
            &out,
            &format!(
                "ALTER TABLE {} ADD FOREIGN KEY ({cols}) REFERENCES {}({refs});",
                q(d, "child"),
                q(d, "parent")
            ),
        );
    }
}

#[test]
fn sql_drop_named_fk_per_dialect() {
    let mut m = modification("child");
    m.fks_removed = vec![fk(Some("fk_child"))];
    let r = schema_with(m);
    assert_line(
        &sql(&r, SqlDialect::MySql),
        "ALTER TABLE `child` DROP FOREIGN KEY `fk_child`;",
    );
    assert_line(
        &sql(&r, SqlDialect::Postgres),
        "ALTER TABLE \"child\" DROP CONSTRAINT \"fk_child\";",
    );
    assert_line(
        &sql(&r, SqlDialect::Mssql),
        "ALTER TABLE [child] DROP CONSTRAINT [fk_child];",
    );
    assert_line(
        &sql(&r, SqlDialect::Sqlite),
        "-- SQLite does not support DROP CONSTRAINT; manual migration required for FK fk_child",
    );
}

#[test]
fn sql_drop_unnamed_fk_is_comment() {
    let mut m = modification("child");
    m.fks_removed = vec![fk(None)];
    let r = schema_with(m);
    for d in ALL {
        let out = sql(&r, d);
        assert_line(
            &out,
            "-- Cannot drop unnamed FK (a, b) -> parent.(x, y) without constraint name",
        );
        assert!(!out.contains("DROP CONSTRAINT"), "{d}: {out}");
        assert!(!out.contains("DROP FOREIGN KEY"), "{d}: {out}");
    }
}

