#[test]
fn sql_added_table_uses_create_statement_and_appends_semicolon() {
    let r = result(
        Some(SchemaDiff {
            tables_added: vec![TableInfo {
                name: "t".into(),
                columns: vec![],
                primary_key: vec![],
                create_statement: Some("  CREATE TABLE t (id INT)  ".into()),
            }],
            tables_removed: vec![],
            tables_modified: vec![],
        }),
        None,
    );
    let out = sql(&r, SqlDialect::MySql);
    assert!(
        out.contains("-- New table: t\nCREATE TABLE t (id INT);\n\n"),
        "{out}"
    );

    // Already-terminated statements are not double-terminated.
    let r2 = result(
        Some(SchemaDiff {
            tables_added: vec![TableInfo {
                name: "t".into(),
                columns: vec![],
                primary_key: vec![],
                create_statement: Some("CREATE TABLE t (id INT);".into()),
            }],
            tables_removed: vec![],
            tables_modified: vec![],
        }),
        None,
    );
    assert!(!sql(&r2, SqlDialect::MySql).contains(";;"));
}

#[test]
fn sql_added_table_synthesizes_create_from_columns() {
    let r = result(
        Some(SchemaDiff {
            tables_added: vec![TableInfo {
                name: "orders".into(),
                columns: vec![col("id", "INT", false), col("note", "TEXT", true)],
                primary_key: strs(&["id"]),
                create_statement: None,
            }],
            tables_removed: vec![],
            tables_modified: vec![],
        }),
        None,
    );
    for d in ALL {
        let out = sql(&r, d);
        let expected = format!(
            "-- New table: orders\nCREATE TABLE {} (\n  {} INT NOT NULL,\n  {} TEXT,\n  PRIMARY KEY ({})\n);\n\n",
            q(d, "orders"),
            q(d, "id"),
            q(d, "note"),
            q(d, "id")
        );
        assert!(out.contains(&expected), "dialect {d}:\n{out}");
    }
}

